"""Build assets/js/papers-data.js from data/papers/*.tsv and data/papers/meta.json.

Each TSV has columns id, cat, note. Titles, authors and dates come from meta.json,
which caches arXiv API results.

Usage:
  python scripts/build_papers.py          # build from the cached metadata
  python scripts/build_papers.py --fetch  # fetch metadata for new ids from arXiv first
"""
import csv
import json
import os
import sys
import time
import urllib.parse
import urllib.request
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "data", "papers")
OUT = os.path.join(ROOT, "assets", "js", "papers-data.js")
ATOM = "{http://www.w3.org/2005/Atom}"

GROUPS = [
    ("classics", "经典基础", "classics.tsv"),
    ("inference", "推理侧：MXFP4 / NVFP4", "inference.tsv"),
    ("training", "训练侧：低精度训练", "training.tsv"),
]

CATEGORIES = [
    ("K1", "classics", "数值格式与混合精度"),
    ("K2", "classics", "权重量化与混合输入 kernel"),
    ("K3", "classics", "激活与 KV cache 量化"),
    ("K4", "classics", "低精度训练与 QAT"),
    ("A", "inference", "格式、基准与误差分析"),
    ("B", "inference", "变换类 PTQ（旋转 / 平滑 / 仿射 / 残差）"),
    ("C", "inference", "尺度与舍入优化"),
    ("D", "inference", "格式扩展与软硬协同"),
    ("E", "inference", "Attention、KV cache 与循环状态"),
    ("F", "inference", "推理模型与 agent 场景"),
    ("G", "inference", "精度恢复：QAD / QAT / on-policy 蒸馏"),
    ("H", "inference", "与投机解码、稀疏等手段组合"),
    ("J", "inference", "扩散与视觉模型"),
    ("I", "inference", "Agent 驱动的量化与 kernel 优化"),
    ("T1", "training", "预训练配方与格式"),
    ("T2", "training", "无偏梯度与训练稳定性"),
    ("T3", "training", "低精度 RL 与训推失配"),
]


def read_rows():
    rows = []
    for group, _, fname in GROUPS:
        with open(os.path.join(DATA, fname), encoding="utf-8", newline="") as f:
            for r in csv.DictReader(f, delimiter="\t"):
                rows.append({"id": r["id"].strip(), "cat": r["cat"].strip(),
                             "note": r["note"].strip(), "group": group})
    return rows


def fetch(ids):
    meta = {}
    for i in range(0, len(ids), 40):
        url = "https://export.arxiv.org/api/query?" + urllib.parse.urlencode(
            {"id_list": ",".join(ids[i:i + 40]), "max_results": 40})
        with urllib.request.urlopen(url, timeout=60) as r:
            root = ET.fromstring(r.read())
        for e in root.findall(ATOM + "entry"):
            aid = e.find(ATOM + "id").text.rsplit("/", 1)[-1].rsplit("v", 1)[0]
            authors = [a.find(ATOM + "name").text.strip() for a in e.findall(ATOM + "author")]
            meta[aid] = {"title": " ".join(e.find(ATOM + "title").text.split()),
                         "date": e.find(ATOM + "published").text[:7],
                         "authors": ", ".join(authors[:3]) + (" et al." if len(authors) > 3 else "")}
        time.sleep(3)
    return meta


def main():
    rows = read_rows()
    meta_path = os.path.join(DATA, "meta.json")
    meta = json.load(open(meta_path, encoding="utf-8")) if os.path.exists(meta_path) else {}

    seen, dupes = set(), []
    for r in rows:
        if r["id"] in seen:
            dupes.append(r["id"])
        seen.add(r["id"])
    if dupes:
        sys.exit(f"duplicate ids across TSV files: {dupes}")
    cats = {c for c, _, _ in CATEGORIES}
    bad = [r["id"] for r in rows if r["cat"] not in cats]
    if bad:
        sys.exit(f"unknown category for: {bad}")

    missing = [r["id"] for r in rows if r["id"] not in meta]
    if missing and "--fetch" in sys.argv:
        meta.update(fetch(missing))
        missing = [r["id"] for r in rows if r["id"] not in meta]
    if missing:
        sys.exit(f"no metadata for {missing}; rerun with --fetch")

    meta = {k: meta[k] for k in sorted(seen)}
    with open(meta_path, "w", encoding="utf-8") as f:
        json.dump(meta, f, ensure_ascii=False, indent=1)
        f.write("\n")

    papers = [{**r, **meta[r["id"]]} for r in rows]
    papers.sort(key=lambda p: (p["date"], p["id"]), reverse=True)
    payload = {
        "groups": [{"id": g, "name": n} for g, n, _ in GROUPS],
        "categories": [{"id": c, "group": g, "name": n} for c, g, n in CATEGORIES],
        "papers": papers,
    }
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("// Generated by scripts/build_papers.py. Edit data/papers/*.tsv instead.\n")
        f.write("window.PAPERS_DATA = ")
        json.dump(payload, f, ensure_ascii=False, separators=(",", ":"))
        f.write(";\n")
    counts = {g: sum(p["group"] == g for p in papers) for g, _, _ in GROUPS}
    print(f"{len(papers)} papers -> {os.path.relpath(OUT, ROOT)} {counts}")


if __name__ == "__main__":
    main()
